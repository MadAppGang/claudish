#!/usr/bin/env python3
"""Fork layer manifest — the layer contract for the v14 re-platform (Epic #641 G0).

Lists every file that exists in the fork ref but NOT in the upstream ref
(machine-derived: `git ls-tree` set difference), with size, layer path and the
first commit that added it. Regenerate, never hand-edit.

    python scripts/fork-layer-manifest.py [FORK_REF] [UPSTREAM_REF] [OUT_PATH]

Defaults: origin/main, upstream/main, docs/reference/replatform-v14-layer-manifest.md
"""
import collections
import subprocess
import sys

FORK = sys.argv[1] if len(sys.argv) > 1 else "origin/main"
UPSTREAM = sys.argv[2] if len(sys.argv) > 2 else "upstream/main"
OUT = sys.argv[3] if len(sys.argv) > 3 else "docs/reference/replatform-v14-layer-manifest.md"


def git(*args: str) -> str:
    # git emits UTF-8; text=True alone decodes with the locale codepage on
    # Windows (cp1252), which turns every em dash in a commit subject into mojibake.
    return subprocess.run(
        ["git", *args], capture_output=True, text=True, encoding="utf-8", check=True
    ).stdout


def rev(ref: str) -> str:
    return git("rev-parse", "--short", ref).strip()


fork_files = set(git("ls-tree", "-r", "--name-only", FORK).splitlines())
upstream_files = set(git("ls-tree", "-r", "--name-only", UPSTREAM).splitlines())
created = sorted(fork_files - upstream_files)
if not created:
    sys.exit("no fork-created files — refs identical or reversed?")

sizes: dict[str, int] = {}
for line in git("ls-tree", "-r", "-l", FORK).splitlines():
    meta, path = line.split("\t", 1)
    sizes[path] = int(meta.split()[3])

# First addition per path: one pass over the log, newest-first, so the LAST
# occurrence of a path is the commit that created it.
want = set(created)
added: dict[str, str] = {}
current = "?"
for line in git(
    "log", "--diff-filter=A", "--name-only", "--format=__C %h %s", FORK
).splitlines():
    if line.startswith("__C "):
        current = line[4:].strip()
    elif line in want:
        added[line] = current


def layer(path: str) -> str:
    parts = path.split("/")
    # packages/<pkg>/src/<component>/... -> packages/<pkg>/src/<component>
    # a file sitting directly in src/ has exactly 4 parts -> packages/<pkg>/src
    if parts[0] == "packages" and len(parts) >= 5 and parts[2] == "src":
        return "/".join(parts[:4])
    if parts[0] == "packages" and len(parts) >= 3:
        return "/".join(parts[:3])
    return parts[0]


per_layer = collections.Counter(layer(p) for p in created)
total_bytes = sum(sizes[p] for p in created)

lines = [
    "# Fork layer manifest — freeze `fork-final-20261024` (Epic #641 G0)",
    "",
    "**Machine-generated by `scripts/fork-layer-manifest.py`. Regenerate, never hand-edit.**",
    "",
    f"- Fork ref: `{rev(FORK)}` (`fork-final-20261024`, the frozen `main`)",
    f"- Upstream ref: `{rev(UPSTREAM)}` (`upstream/main`, v14.4.1)",
    f"- Fork-created files (present in the fork, absent upstream): **{len(created)}** — "
    f"{format(total_bytes, ',').replace(',', ' ')} bytes total",
    "- Re-check (the G0 gate): the path column below must equal",
    "  `comm -23 <(git ls-tree -r --name-only <fork> | sort) <(git ls-tree -r --name-only <upstream> | sort)`.",
    "",
    "## Files per layer",
    "",
    "| layer | files |",
    "|---|---|",
]
for name, count in sorted(per_layer.items(), key=lambda kv: (-kv[1], kv[0])):
    lines.append(f"| `{name}` | {count} |")

lines += [
    "",
    "## The contract",
    "",
    "| path | bytes | layer | first added by |",
    "|---|---|---|---|",
]
for path in created:
    purpose = added.get(path, "?").replace("|", "\\|")
    if len(purpose) > 120:
        purpose = purpose[:117] + "..."
    lines.append(f"| `{path}` | {sizes[path]} | `{layer(path)}` | {purpose} |")

lines.append("")
with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))
print(f"wrote {OUT}: {len(created)} files, {total_bytes} bytes")
