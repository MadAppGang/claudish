#!/usr/bin/env bun
/**
 * Write cli.experiment.yaml and mcp.experiment.yaml from the recommended list.
 *
 *   bun ai-docs/benches/recommended-models/scripts/gen-experiments.ts
 *
 * The list is read from `claudish --models-top --json`, never typed here: it
 * changes with every catalog generation, and a hand-kept copy is the hardcoded
 * model data CLAUDE.md forbids. Re-run this before a real run.
 *
 * Two kinds of variant, in this order:
 *   1. every recommended model by its bare name, so routing chooses the hop the
 *      user would get (the first one is the Experiment's baseline);
 *   2. every distinct subscription command the list publishes (`cx@gpt-6.1-sol`,
 *      `kc@k3`), so each subscription connection is exercised on its own. A row
 *      with no provider shortcut is the native route and is already in (1).
 */
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

interface Subscription {
  prefix?: string;
  command: string;
}
interface RecommendedModel {
  id: string;
  category: string;
  subscriptions?: Subscription[];
}
interface RecommendedDoc {
  generationId: string;
  models: RecommendedModel[];
}

const BENCH_DIR = resolve(import.meta.dir, "..");

const proc = Bun.spawnSync(["claudish", "--models-top", "--json"], { stderr: "inherit" });
if (proc.exitCode !== 0) {
  console.error(`claudish --models-top --json exited ${proc.exitCode}`);
  process.exit(1);
}
const doc = JSON.parse(proc.stdout.toString()) as RecommendedDoc;

const variants: Array<{ name: string; model: string }> = [];
const seenModels = new Set<string>();
const add = (model: string) => {
  if (seenModels.has(model)) return;
  seenModels.add(model);
  // The variant is named by its model spec, `@` and all: madbench accepts it in
  // the file and in `--variant 'oc@glm-5.3'`, and the report then names the
  // exact spec that was sent.
  variants.push({ name: model, model });
};

for (const m of doc.models) if (m.category !== "subscription") add(m.id);
for (const m of doc.models) {
  if (m.category !== "subscription") continue;
  for (const s of m.subscriptions ?? []) if (s.prefix) add(s.command);
}

const header = (bench: string) =>
  [
    `# GENERATED by scripts/gen-experiments.ts from \`claudish --models-top --json\`.`,
    `# Catalog generation ${doc.generationId}, written ${new Date().toISOString()}.`,
    `# Do not edit by hand: re-run the script. ${variants.length} variants.`,
    `description: ${JSON.stringify(`${bench}: every recommended model and subscription command`)}`,
    `bench: ./${bench}.madbench.yaml`,
  ].join("\n");

const variantLines = variants
  .map((v) => `  - name: ${JSON.stringify(v.name)}\n    params: { model: ${JSON.stringify(v.model)} }`)
  .join("\n");

// The CLI Bench passes the model as harness.model, so the variants differ there
// and only there. The MCP Bench keeps harness.model fixed (the model under test
// is in the prompt and the Checks), so its staged inputs never differ.
const cli = `${header("cli")}
guard_changes:
  allow: [harness/model]
variants:
${variantLines}
`;
const mcp = `${header("mcp")}
variants:
${variantLines}
`;

writeFileSync(join(BENCH_DIR, "cli.experiment.yaml"), cli);
writeFileSync(join(BENCH_DIR, "mcp.experiment.yaml"), mcp);
console.log(`generation ${doc.generationId}: ${variants.length} variants`);
for (const v of variants) console.log(`  ${v.name}`);
